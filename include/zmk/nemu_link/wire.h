#define NEMU_LINK_MINI_COUNTER_SIZE 2U
#define NEMU_LINK_MINI_COUNTER_BITS (NEMU_LINK_MINI_COUNTER_SIZE * NEMU_LINK_RADIO_BITS_PER_BYTE)
