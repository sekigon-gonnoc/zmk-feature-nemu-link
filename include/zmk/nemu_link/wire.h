/* Authenticated flags share the kind byte; packet sizes stay 7/9 bytes. */
#define NEMU_LINK_MINI_STUDIO_PENDING 0x80U
#define NEMU_LINK_LINK_STUDIO_PENDING 0x80U
#define NEMU_LINK_COMPACT_STUDIO_PENDING 0x01U

/* Length8/S1=3 is fixed by the ESB DMA hook; wait one extra byte so all
 * counter bytes are in RAM before the bit-counter IRQ reads the prefix. */
#define NEMU_LINK_RADIO_LENGTH_BITS 8U
#define NEMU_LINK_RADIO_S1_BITS 3U
#define NEMU_LINK_RADIO_BITS_PER_BYTE 8U
#define NEMU_LINK_RADIO_PREFIX_GUARD_SIZE 1U
#define NEMU_LINK_RADIO_PREFIX_BITS(header_size)                                                   \
    (NEMU_LINK_RADIO_LENGTH_BITS + NEMU_LINK_RADIO_S1_BITS +                                       \
     ((header_size) + NEMU_LINK_RADIO_PREFIX_GUARD_SIZE) * NEMU_LINK_RADIO_BITS_PER_BYTE)
#define NEMU_LINK_RADIO_MINI_PREFIX_BITS NEMU_LINK_RADIO_PREFIX_BITS(NEMU_LINK_MINI_COUNTER_SIZE)
#define NEMU_LINK_RADIO_FULL_PREFIX_BITS NEMU_LINK_RADIO_PREFIX_BITS(NEMU_LINK_COMPACT_HEADER_SIZE)

_Static_assert((NEMU_LINK_RADIO_RX_PDU_OFFSET + NEMU_LINK_RADIO_PDU_HEADER_SIZE +
                NEMU_LINK_MINI_COUNTER_SIZE - NEMU_LINK_CCM_DMA_HEADER_SIZE) %
                       sizeof(uint32_t) ==
                   0,
               "mini RX CCM header aligned");
_Static_assert((NEMU_LINK_RADIO_RX_PDU_OFFSET + NEMU_LINK_RADIO_PDU_HEADER_SIZE +
                NEMU_LINK_COMPACT_HEADER_SIZE - NEMU_LINK_CCM_DMA_HEADER_SIZE) %
                       sizeof(uint32_t) ==
                   0,
               "full RX CCM header aligned");
